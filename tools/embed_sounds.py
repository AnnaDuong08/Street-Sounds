"""Pack every MP3 in sounds/ into js/sounds.js so the site can play them from local files.

Browsers block fetch() and <audio> + Web Audio on file:// pages, so the recordings are
embedded as base64 instead. Run this again whenever you add or replace a file in sounds/:

    python3 tools/embed_sounds.py

The file name (without .mp3) is the key: banhmi, hotvitlon, che, hutieugo, banhgio, banhbao,
and later moto, rain, bell, crickets. Uses only the Python standard library.
"""
import base64
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
clips = sorted((root / "sounds").glob("*.mp3"))
lines = ["/* Generated by tools/embed_sounds.py from the files in sounds/. Do not edit by hand. */",
         "window.SOUND_DATA = {"]
for f in clips:
    lines.append(f'  "{f.stem}": "{base64.b64encode(f.read_bytes()).decode()}",')
lines.append("};")
(root / "js" / "sounds.js").write_text("\n".join(lines) + "\n")
print(f"js/sounds.js: {len(clips)} clips ({', '.join(f.stem for f in clips)})")
